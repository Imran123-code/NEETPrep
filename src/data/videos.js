// Helper Query Functions
export const getAllVideos = () => neetVideos;

export const getVideoById = (id) => {
  if (!id) return null;
  return neetVideos.find(v => v.id.toLowerCase() === id.toLowerCase() || v.youtubeId === id) || null;
};

export const getVideosByChapter = (chapterId) => {
  if (!chapterId || chapterId === 'All') return neetVideos;
  return neetVideos.filter(v => v.chapterId.toLowerCase() === chapterId.toLowerCase());
};

export const getVideosBySubject = (subject) => {
  if (!subject || subject === 'All') return neetVideos;
  return neetVideos.filter(v => v.subject.toLowerCase() === subject.toLowerCase());
};

export const getVideosByClass = (classNum) => {
  if (!classNum || classNum === 'All') return neetVideos;
  const num = parseInt(classNum, 10);
  return neetVideos.filter(v => v.class === num);
};

export const getVideosByTopic = (chapterId, topic) => {
  let list = neetVideos;
  if (chapterId && chapterId !== 'All') {
    list = list.filter(v => v.chapterId.toLowerCase() === chapterId.toLowerCase());
  }
  if (topic && topic !== 'All') {
    const q = topic.toLowerCase();
    list = list.filter(v => 
      v.topic.toLowerCase().includes(q) || 
      v.title.toLowerCase().includes(q) ||
      v.tags.some(t => t.toLowerCase().includes(q))
    );
  }
  return list;
};

export const getRelatedVideos = (currentVideo, limit = 4) => {
  if (!currentVideo) return neetVideos.slice(0, limit);
  return neetVideos
    .filter(v => v.id !== currentVideo.id && (v.chapterId === currentVideo.chapterId || v.subject === currentVideo.subject))
    .slice(0, limit);
};

// Generates direct YouTube search URL for any chapter or topic
export const getYouTubeSearchUrl = (query) => {
  const safeQuery = encodeURIComponent(query.trim());
  return `https://www.youtube.com/results?search_query=${safeQuery}`;
};

// Dynamic search handler with optional YouTube Data API v3 support
export const searchYouTubeVideos = async ({ query, subject, classNum, chapterName, topic }) => {
  const constructedQuery = [
    'NEET',
    classNum ? `Class ${classNum}` : '',
    subject || '',
    chapterName || '',
    topic || '',
    query || '',
  ].filter(Boolean).join(' ');

  const apiKey = import.meta.env?.VITE_YOUTUBE_API_KEY;

  if (apiKey) {
    try {
      const endpoint = `https://www.googleapis.com/youtube/v3/search?part=snippet&maxResults=12&q=${encodeURIComponent(
        constructedQuery
      )}&type=video&videoEmbeddable=true&key=${apiKey}`;
      
      const response = await fetch(endpoint);
      if (response.ok) {
        const data = await response.json();
        if (data.items && data.items.length > 0) {
          return {
            source: 'api',
            query: constructedQuery,
            youtubeSearchUrl: getYouTubeSearchUrl(constructedQuery),
            items: data.items.map((item, index) => ({
              id: `yt-${item.id.videoId}`,
              subject: subject || 'General',
              class: classNum ? parseInt(classNum, 10) : 11,
              chapterId: '',
              chapterName: chapterName || '',
              topic: topic || item.snippet.title,
              title: item.snippet.title,
              youtubeId: item.id.videoId,
              channel: item.snippet.channelTitle,
              videoType: 'Concept',
              language: 'Hinglish',
              difficulty: 'Intermediate',
              duration: 'Video Lecture',
              views: 'Live YouTube',
              badge: 'Recommended',
              description: item.snippet.description,
              tags: ['NEET', subject, chapterName].filter(Boolean),
            })),
          };
        }
      }
    } catch (e) {
      console.warn('YouTube API query failed, falling back to curated library:', e);
    }
  }

  // Graceful curated fallback: filter our database
  let matched = neetVideos;
  if (subject && subject !== 'All') {
    matched = matched.filter(v => v.subject.toLowerCase() === subject.toLowerCase());
  }
  if (classNum && classNum !== 'All') {
    const num = parseInt(classNum, 10);
    matched = matched.filter(v => v.class === num);
  }
  if (chapterName) {
    const ch = chapterName.toLowerCase();
    matched = matched.filter(v => v.chapterName.toLowerCase().includes(ch) || v.chapterId.includes(ch));
  }
  if (topic) {
    const t = topic.toLowerCase();
    matched = matched.filter(v => 
      v.topic.toLowerCase().includes(t) || 
      v.title.toLowerCase().includes(t) || 
      v.tags.some(tag => tag.toLowerCase().includes(t))
    );
  }
  if (query) {
    const q = query.toLowerCase();
    matched = matched.filter(v =>
      v.title.toLowerCase().includes(q) ||
      v.description.toLowerCase().includes(q) ||
      v.channel.toLowerCase().includes(q) ||
      v.tags.some(tag => tag.toLowerCase().includes(q))
    );
  }

  return {
    source: 'curated',
    query: constructedQuery,
    youtubeSearchUrl: getYouTubeSearchUrl(constructedQuery),
    items: matched,
  };
};
